/// Resolve an oracle logical opcode to its Microsoft table and slot.
pub fn microsoft_identity(
    logical_opcode: u16,
) -> Result<crate::program::MicrosoftOpcodeId, String> {
    let prefix = *LOGICAL_OPCODE_PREFIX
        .get(usize::from(logical_opcode))
        .ok_or_else(|| format!("logical opcode 0x{logical_opcode:X} is outside FAC2090"))?;
    let (table, opcode) = match prefix {
        0xFB => (crate::DispatchTable::Lead0, logical_opcode as u8),
        0xFC => (crate::DispatchTable::Lead1, logical_opcode as u8),
        0xFD => (crate::DispatchTable::Lead2, logical_opcode as u8),
        0xFE => (crate::DispatchTable::Lead3, logical_opcode as u8),
        0xFF => (crate::DispatchTable::Lead4, logical_opcode as u8),
        byte => (crate::DispatchTable::Primary, byte),
    };
    Ok(crate::program::MicrosoftOpcodeId::new(table, opcode))
}

/// Encode a FAC2090 logical opcode as its Microsoft dispatch bytes.
pub fn encode_logical_opcode(logical_opcode: u16) -> Result<Vec<u8>, String> {
    let id = microsoft_identity(logical_opcode)?;
    Ok(match id.table.prefix() {
        Some(prefix) => vec![prefix, id.opcode],
        None => vec![id.opcode],
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn resolves_primary_and_prefixed_logical_opcodes() {
        assert_eq!(
            microsoft_identity(0x90).unwrap(),
            crate::program::MicrosoftOpcodeId::new(crate::DispatchTable::Primary, 0xaa)
        );
        assert_eq!(encode_logical_opcode(0x90).unwrap(), [0xaa]);
        assert_eq!(
            microsoft_identity(0x11).unwrap(),
            crate::program::MicrosoftOpcodeId::new(crate::DispatchTable::Lead0, 0x11)
        );
        assert_eq!(encode_logical_opcode(0x11).unwrap(), [0xfb, 0x11]);
    }

    #[test]
    fn rejects_logical_opcodes_beyond_the_recovered_table() {
        assert!(microsoft_identity(0x447).is_err());
        assert!(encode_logical_opcode(0x447).is_err());
    }
}
