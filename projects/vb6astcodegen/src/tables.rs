/// Raw lookup used by FAC16ED..FAC1703; this does not assert type legality.
pub fn address_mode4_byte(ty: u16, flags: u32) -> Option<(u32, u8)> {
    let index = *TYPE_INDEX.get(ty as usize)? as i32;
    let offset = ((((!flags >> 12) & 1) as i32) - 12 + index * 2) * 2 + ((!flags >> 11) & 1) as i32;
    let address = (0x0fac29d8i64 + offset as i64) as u32;
    let byte = *ADDRESS_LOOKUP_BYTES.get(address.checked_sub(0x0fac29b0)? as usize)?;
    Some((address, byte))
}
