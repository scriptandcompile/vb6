#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SelectionError {
    UnknownKind(u16),
    UnknownType(u16),
    NoTypedBase(u16),
    MissingSlot,
    UnknownOpcode(u16),
    TruncatedOpcode,
}
pub fn normalized_type(ty: u16) -> Result<u16, SelectionError> {
    let n = *TYPE_INDEX
        .get(ty as usize)
        .ok_or(SelectionError::UnknownType(ty))?;
    Ok(match n {
        9 => 1,
        10 => 4,
        _ => n,
    })
}
#[derive(Debug, Clone, Copy)]
pub struct TypedInput {
    pub kind: u16,
    pub result_type: u16,
    pub left_type: u16,
    pub right_type: Option<u16>,
    pub flags: u32,
    pub slot: Option<u16>,
}
pub fn select_typed(n: TypedInput) -> Result<(u16, Option<u16>), SelectionError> {
    let base = *OPCODE_BASE
        .get(n.kind as usize)
        .ok_or(SelectionError::UnknownKind(n.kind))?;
    if base == 0x446 {
        return Err(SelectionError::NoTypedBase(n.kind));
    }
    let h = n.flags & 0x8000 != 0;
    let delta = if AST_FLAGS[n.kind as usize] & 0x10 == 0 {
        normalized_type(n.result_type)?
    } else if n.kind != 0x72 && n.result_type == 3 && n.left_type == 15 {
        if h { 11 } else { 10 }
    } else if n.left_type == 13 && matches!(n.right_type, Some(10..=12)) {
        12
    } else {
        normalized_type(n.left_type)? + if h { 2 } else { 0 }
    };
    Ok((
        base + delta,
        if n.result_type == 15 {
            Some(n.slot.ok_or(SelectionError::MissingSlot)?)
        } else {
            None
        },
    ))
}
/// FAC0C18/FAC0AD4 codec. Record byte 1 is metadata, not extended byte 1.
pub fn encode_opcode(op: u16) -> Result<Vec<u8>, SelectionError> {
    let (prefix, _) = *OPCODE_RECORDS
        .get(op as usize)
        .ok_or(SelectionError::UnknownOpcode(op))?;
    Ok(if prefix < 0xfb {
        vec![prefix]
    } else {
        vec![prefix, op as u8]
    })
}
pub fn decode_opcode(bytes: &[u8]) -> Result<(u16, usize), SelectionError> {
    let prefix = *bytes.first().ok_or(SelectionError::TruncatedOpcode)?;
    if prefix < 0xfb {
        Ok((CANONICAL_SHORT[prefix as usize], 1))
    } else {
        let low = *bytes.get(1).ok_or(SelectionError::TruncatedOpcode)?;
        Ok((((prefix - 0xfb) as u16) * 256 + low as u16, 2))
    }
}
