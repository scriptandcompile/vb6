//! Separate statement namespace: byte tag at statement+0x10, NOT expression low-u16 tag.
//! Catalog descriptors do not execute helpers, AST traversal, backpatches or procedure finalization.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum StatementCoverage {
    Partial,
    Unknown,
}
#[derive(Debug, Clone, Copy)]
pub struct FixedStatementDecision {
    pub opcode: u16,
    pub guard: &'static str,
    pub operands: &'static str,
    pub called_function: u32,
    pub source_line: u16,
}
#[derive(Debug, Clone, Copy)]
pub struct StatementFormula {
    pub guard: &'static str,
    pub formula: &'static str,
    pub source_line: u16,
    pub requires_resolved_descriptor: bool,
}
