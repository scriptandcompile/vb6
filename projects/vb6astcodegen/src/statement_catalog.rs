pub fn statement_record(tag: u8) -> Option<&'static StatementRecord> {
    tag.checked_sub(1)
        .and_then(|i| STATEMENT_CATALOG.get(i as usize))
}
pub const fn statement_type_offset(type_index: u32) -> u32 {
    match type_index {
        10 => 4,
        9 => 1,
        other => other,
    }
}
/// Guard bit0 determines base; this does not validate operand type legality.
pub const fn statement_loop_opcode(type_index: u32, flag_bit0: bool, closing: bool) -> u32 {
    let base = match (closing, flag_bit0) {
        (false, false) => 0x36a,
        (false, true) => 0x362,
        (true, false) => 0x380,
        (true, true) => 0x378,
    };
    base + statement_type_offset(type_index)
}
