use crate::{
    addressing as ad, assignment as assign, cleanup as cl, conversions as cv, member_calls as mc,
    tables,
};
use std::collections::{BTreeMap, BTreeSet};
pub type NodeId = usize;

#[derive(Debug, Clone, Default)]
pub enum Literal {
    #[default]
    None,
    Integer(i32),
    /// Raw little-endian bytes at native node+0x10; floating payload is f64.
    Raw64([u8; 8]),
    Variant {
        tag: u16,
        bytes: [u8; 8],
        string_reference: Option<u32>,
    },
    SpecialWord(u16),
}
#[derive(Debug, Clone, Copy)]
pub enum Member {
    Direct(u32),
    Reference(u32),
}
#[derive(Debug, Clone, Default)]
pub struct Node {
    pub kind: u16,
    pub type_id: u16,
    /// Native dword node[1], offset +4. Not AST_FLAGS[kind].
    pub flags: u32,
    pub left: Option<NodeId>,
    pub right: Option<NodeId>,
    /// Native node[6] for storage-slot resolution.
    pub symbol: Option<u32>,
    /// Native node[5] when interpreted as a bound handle, not a child pointer.
    pub reference: Option<u32>,
    /// Native node[7] for member/ref operands.
    pub member: Option<Member>,
    pub count: u16,
    pub layout_count: u16,
    pub literal: Literal,
}
impl Node {
    pub fn integer(type_id: u16, value: i32) -> Self {
        Self {
            kind: 1,
            type_id,
            literal: Literal::Integer(value),
            ..Self::default()
        }
    }
    pub fn operator(kind: u16, type_id: u16, left: NodeId, right: Option<NodeId>) -> Self {
        Self {
            kind,
            type_id,
            left: Some(left),
            right,
            ..Self::default()
        }
    }
}
#[derive(Debug, Clone, Default)]
pub struct Ast {
    pub nodes: Vec<Node>,
}
impl Ast {
    pub fn push(&mut self, node: Node) -> NodeId {
        let id = self.nodes.len();
        self.nodes.push(node);
        id
    }
}
#[derive(Debug, Clone, Default)]
pub struct Bindings {
    /// Results of FAAB81F, supplied by a binder/context rather than invented.
    pub slots: BTreeMap<u32, u16>,
    /// Results of FAC2E29; callers own reference-pool allocation/relocations.
    pub references: BTreeMap<u32, u16>,
    pub symbol_types: BTreeMap<u32, u16>,
    /// Bound nodes returned by FAB5210, keyed by symbol.
    pub bound_nodes: BTreeMap<u32, NodeId>,
    pub conversion_metadata: BTreeMap<NodeId, cv::ResolvedConversionMetadata>,
    /// Two property queries FAB5494/FAB54AE, keyed by native node[2] surrogate NodeId.
    pub property_checks: BTreeMap<NodeId, (bool, bool)>,
    /// Final descriptors from the native reference preparation phase. This
    /// representation is valid only when that preparation emits no prefix.
    /// Emitters requiring side-effectful preparation remain unresolved.
    pub prepared_addresses: BTreeMap<NodeId, ad::AddressDescriptor>,
    pub address_metadata: BTreeMap<NodeId, ad::AddressMetadata>,
    pub assignment_metadata: BTreeMap<NodeId, assign::ResolvedAssignmentMetadata>,
    pub cleanup_metadata: BTreeMap<NodeId, cl::CleanupListInput>,
    pub symbol_special: BTreeMap<NodeId, bool>,
    pub member_metadata: BTreeMap<NodeId, mc::ResolvedMemberMetadata>,
    /// Active DAT_0FC10330 values, if different from the supplied snapshot.
    pub member_base_table: Option<[u16; 6]>,
    /// Successful descriptor or native failure from FAC35B5's signature path:
    /// FEE191/FAC3945. Kept distinct from storage-slot allocation.
    pub signature_descriptors: BTreeMap<NodeId, Result<u16, i32>>,
    /// Bound native record data for storage classes1..3. Descriptors and reference
    /// preparation are computed by codegen for these classes.
    pub storage_references: BTreeMap<NodeId, crate::references::CommonStorageReference>,
    /// Full FAC0FA8 record/descriptor information, including environment and
    /// remote-reference helper outcomes. Prefixes are generated by this crate.
    pub native_references: BTreeMap<NodeId, crate::references::ResolvedReference>,
    /// Captured native pointer low words for ReDim fallback; never arena indices.
    pub native_pointer_words: BTreeMap<NodeId, u16>,
}
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum EmitError {
    MissingNode(NodeId),
    MissingChild(NodeId, &'static str),
    MissingBinding(NodeId, &'static str),
    InvalidPayload(NodeId),
    NativeHelperFailure {
        node: NodeId,
        function: u32,
        status: i32,
    },
    Cycle(NodeId),
    RecursionLimit,
    OutputTooLarge,
    Unresolved {
        node: NodeId,
        kind: u16,
        function: u32,
    },
    Selection(tables::SelectionError),
    Conversion(cv::ConversionError),
    Address(ad::AddressError),
    Assignment(assign::AssignmentError),
    Cleanup(cl::CleanupError),
    Member(mc::MemberError),
    Reference(crate::references::ReferenceError),
    /// A raw C decompiler variable has no established value outside this domain.
    UnsupportedType {
        node: NodeId,
        type_id: u16,
    },
}
impl From<tables::SelectionError> for EmitError {
    fn from(e: tables::SelectionError) -> Self {
        Self::Selection(e)
    }
}
impl From<cv::ConversionError> for EmitError {
    fn from(e: cv::ConversionError) -> Self {
        Self::Conversion(e)
    }
}
impl From<ad::AddressError> for EmitError {
    fn from(e: ad::AddressError) -> Self {
        Self::Address(e)
    }
}
impl From<assign::AssignmentError> for EmitError {
    fn from(e: assign::AssignmentError) -> Self {
        Self::Assignment(e)
    }
}
impl From<cl::CleanupError> for EmitError {
    fn from(e: cl::CleanupError) -> Self {
        Self::Cleanup(e)
    }
}
impl From<mc::MemberError> for EmitError {
    fn from(e: mc::MemberError) -> Self {
        Self::Member(e)
    }
}
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Instruction {
    pub node: NodeId,
    pub logical_opcode: u16,
    pub operands: Vec<u8>,
    pub original_function: u32,
}
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Emission {
    pub bytes: Vec<u8>,
    pub instructions: Vec<Instruction>,
    pub native_return: u32,
}
/// Transactional emission: on error no partial stream is returned.
/// An AST kind alone never supplies type, flags, operands, or bound symbol metadata.
pub fn emit_ast(
    ast: &Ast,
    root: NodeId,
    mode: i32,
    bindings: &Bindings,
) -> Result<Emission, EmitError> {
    let mut e = Emitter {
        ast: ast.clone(),
        bindings,
        out: Emission {
            bytes: vec![],
            instructions: vec![],
            native_return: 0,
        },
        active: BTreeSet::new(),
        preparing: BTreeSet::new(),
    };
    e.out.native_return = e.visit(root, mode)?;
    Ok(e.out)
}
struct Emitter<'a> {
    /// Native flag rewrites are simulated on a private copy, preserving
    /// repeated-node behavior within this compilation without mutating caller AST.
    ast: Ast,
    bindings: &'a Bindings,
    out: Emission,
    active: BTreeSet<NodeId>,
    preparing: BTreeSet<NodeId>,
}
impl Emitter<'_> {
    fn get(&self, id: NodeId) -> Result<&Node, EmitError> {
        self.ast.nodes.get(id).ok_or(EmitError::MissingNode(id))
    }
    fn child(&self, id: NodeId, side: &'static str) -> Result<NodeId, EmitError> {
        let n = self.get(id)?;
        if side == "left" { n.left } else { n.right }.ok_or(EmitError::MissingChild(id, side))
    }
    fn slot(&self, id: NodeId) -> Result<u16, EmitError> {
        let n = self.get(id)?;
        n.symbol
            .and_then(|h| self.bindings.slots.get(&h).copied())
            .ok_or(EmitError::MissingBinding(id, "FUN_0faab81f(node[6])"))
    }
    fn reference(&self, id: NodeId) -> Result<u16, EmitError> {
        let n = self.get(id)?;
        n.reference
            .and_then(|h| self.bindings.references.get(&h).copied())
            .ok_or(EmitError::MissingBinding(id, "FUN_0fac2e29"))
    }
    fn word_binding(&self, id: NodeId, h: u32) -> Result<u16, EmitError> {
        self.bindings
            .slots
            .get(&h)
            .copied()
            .ok_or(EmitError::MissingBinding(id, "FUN_0faab81f"))
    }
    fn op(
        &mut self,
        id: NodeId,
        opcode: u16,
        payload: &[u8],
        function: u32,
    ) -> Result<(), EmitError> {
        let bytes = tables::encode_opcode(opcode)?;
        if self.out.bytes.len() + bytes.len() + payload.len() > 65535 {
            return Err(EmitError::OutputTooLarge);
        }
        self.out.bytes.extend(bytes);
        self.out.bytes.extend_from_slice(payload);
        self.out.instructions.push(Instruction {
            node: id,
            logical_opcode: opcode,
            operands: payload.to_vec(),
            original_function: function,
        });
        Ok(())
    }
    fn plain(&mut self, id: NodeId, opcode: u16) -> Result<(), EmitError> {
        self.op(id, opcode, &[], 0x0fabf2d2)
    }
    fn word(&mut self, id: NodeId, opcode: u16, operand: u16) -> Result<(), EmitError> {
        self.op(id, opcode, &operand.to_le_bytes(), 0x0fabf2d2)
    }
    /// FAC0B67 returns 1 for retained floating results; it is not an opcode.
    fn adjustment(
        &mut self,
        id: NodeId,
        type_id: u16,
        source: i32,
        mode: i32,
    ) -> Result<u32, EmitError> {
        let (op, ret) = match type_id {
            2 if source == 0x17 => (Some(0x18b), 0),
            10..=12 if mode != 1 && mode != 3 => (None, 1),
            10 => (Some(0x189), 0),
            11 | 12 => (Some(0x18a), 0),
            15 if mode == 3 => (Some(0x18c), 0),
            _ => (None, 0),
        };
        if let Some(op) = op {
            self.op(id, op, &[], 0x0fac0b67)?
        }
        Ok(ret)
    }
    fn visit(&mut self, id: NodeId, mode: i32) -> Result<u32, EmitError> {
        if self.active.len() >= 256 {
            return Err(EmitError::RecursionLimit);
        }
        if !self.active.insert(id) {
            return Err(EmitError::Cycle(id));
        }
        let result = self.dispatch(id, mode);
        self.active.remove(&id);
        result
    }
    fn dispatch(&mut self, id: NodeId, mode: i32) -> Result<u32, EmitError> {
        let n = self.get(id)?.clone();
        let h = n.flags & 0x8000 != 0;
        // Use the complete numeric route table. Some source tags deliberately
        // return no bytes in the native dispatcher, but still require an earlier
        // lowering/binding pass before that behavior is safe to accept here.
        let Some(rule) = crate::emission_rules::ast_emission_rule(n.kind) else {
            return Err(self.unresolved(id, 0x0fabf2d2));
        };
        if matches!(
            rule.path,
            crate::emission_rules::EmissionPath::RuntimeBuiltinLowering { .. }
        ) {
            return Err(self.unresolved(id, rule.selection_entry.unwrap_or(0x0faec8d3)));
        }
        // Named-argument and argument-binding nodes are consumed by the binder.
        // A no-op here could silently drop a value from the generated call.
        if matches!(n.kind, 0x70 | 0x71) {
            return Err(self.unresolved(id, rule.selection_entry.unwrap_or(0x0fabf2d2)));
        }
        if matches!(
            rule.path,
            crate::emission_rules::EmissionPath::NoDirectEmission
        ) {
            return Ok(0);
        }
        match n.kind {
            1 => {
                let v = match n.literal {
                    Literal::Integer(v) => v,
                    _ => return Err(EmitError::InvalidPayload(id)),
                };
                match n.type_id {
                    3 | 5 | 6 if (-128..=127).contains(&v) => {
                        self.op(id, 0x41a, &[v as u8], 0x0fabf2d2)?
                    }
                    3 | 5 | 6 => self.word(id, 0x3b5, v as u16)?,
                    8 | 16 => self.op(id, 0x3b8, &v.to_le_bytes(), 0x0fabf2d2)?,
                    22 => self.plain(id, 0x163)?,
                    _ => {}
                }
                Ok(0)
            }
            2 => {
                let b = self.raw64(id)?;
                self.op(id, 0x3bb, &b, 0x0fabf2d2)?;
                Ok(0)
            }
            3 => {
                let b = self.raw64(id)?;
                let ty = n.type_id;
                if !(10..=12).contains(&ty) {
                    return Err(EmitError::UnsupportedType {
                        node: id,
                        type_id: ty,
                    });
                }
                let opcode = if ty == 10 {
                    if mode == 2 { 0x3ba } else { 0x3b9 }
                } else if mode == 2 {
                    0x3bd
                } else {
                    0x3bc
                };
                let b = if ty == 10 {
                    (f64::from_le_bytes(b) as f32).to_le_bytes().to_vec()
                } else {
                    b.to_vec()
                };
                self.op(id, opcode, &b, 0x0fabf2d2)?;
                Ok(u32::from(mode == 2))
            }
            4 => {
                if h {
                    self.op(id, 0x3b8, &0u32.to_le_bytes(), 0x0fabf2d2)?
                } else {
                    self.word(id, 0x3bf, self.reference(id)?)?
                }
                Ok(0)
            }
            5 => {
                self.variant(id, mode)?;
                Ok(0)
            }
            6..=10 | 0x16 | 0x17 | 0x19 | 0x1d..=0x23 | 0x25..=0x2b => self.typed(id, mode),
            11 => {
                let child = self.child(id, "left")?;
                self.visit(child, 2)?;
                self.plain(
                    id,
                    0xf2 + tables::normalized_type(self.get(child)?.type_id)?,
                )?;
                Ok(0)
            }
            12 | 13 => {
                let child = self.child(id, "left")?;
                self.visit(child, 1)?;
                let ty = self.get(child)?.type_id;
                let b = if n.kind == 12 { 0xeb } else { 0xed };
                let mut source = 0;
                if ty == 15 {
                    self.word(id, b, self.slot(id)?)?;
                    source = 0x17
                } else if ty == 16 {
                    self.plain(id, b + 1)?
                }
                self.adjustment(id, n.type_id, source, mode)?;
                Ok(0)
            }
            14 => self.conversion(id, mode),
            15 => self.load_address_or_value(id, mode),
            0x10 => {
                self.visit(self.child(id, "left")?, 1)?;
                self.plain(id, 0x135)?;
                Ok(0)
            }
            0x11 => {
                self.value_wrapper(self.child(id, "left")?, 5)?;
                Ok(0)
            }
            0x12 => {
                let child = self.child(id, "left")?;
                let c = self.get(child)?.clone();
                if n.type_id == 22 && c.kind == 0x67 {
                    self.visit(self.child(child, "left")?, 5)?;
                    self.word(id, 0x2f6 + u16::from(mode == 6), self.reference(child)?)?;
                } else if n.type_id == 15 && c.type_id == 23 {
                    self.visit(child, 2)?;
                } else if n.type_id == 23 && c.type_id == 23 {
                    self.visit(child, mode)?;
                    self.plain(id, 0x15c)?;
                } else if c.kind == 0x3f {
                    self.visit(child, mode)?;
                }
                Ok(0)
            }
            0x13 => {
                self.visit(self.child(id, "right")?, 1)?;
                self.plain(id, 0x397)?;
                Ok(0)
            }
            0x14 => {
                if n.type_id == 15 {
                    self.visit(self.child(id, "left")?, 3)?;
                    self.plain(id, 0x3f9)?;
                } else if n.type_id == 23 {
                    let ty = n
                        .symbol
                        .and_then(|h| self.bindings.symbol_types.get(&h).copied())
                        .ok_or(EmitError::MissingBinding(id, "FUN_0fb0f0f7"))?;
                    if ty == 15 {
                        self.visit(self.child(id, "left")?, 1)?;
                        self.plain(id, 0x3fa)?;
                    }
                }
                Ok(0)
            }
            0x15 => {
                let ty = self.get(self.child(id, "left")?)?.type_id;
                self.plain(id, if ty == 15 { 0x42e } else { 0x42d })?;
                Ok(0)
            }
            0x18 if n.type_id != 13 => self.typed(id, mode),
            0x18 => {
                let l = self.child(id, "left")?;
                let r = self.child(id, "right")?;
                self.visit(l, 2)?;
                self.visit(r, 2)?;
                self.plain(
                    id,
                    if self.get(r)?.type_id == 6 {
                        0xd1
                    } else {
                        0xb3
                    },
                )?;
                Ok(0)
            }
            0x1a => {
                self.visit(self.child(id, "left")?, 2)?;
                self.visit(self.child(id, "right")?, 2)?;
                if n.type_id == 15 {
                    self.word(id, 0xce, self.slot(id)?)?
                } else {
                    self.plain(id, 0xcf)?
                }
                self.adjustment(id, n.type_id, 0, mode)
            }
            0x24 => {
                self.visit(self.child(id, "left")?, 1)?;
                self.visit(self.child(id, "right")?, 1)?;
                if n.type_id == 15 {
                    self.word(id, 0xef, self.slot(id)?)?
                } else if n.type_id == 16 {
                    self.plain(id, 0xf0)?
                }
                self.adjustment(id, n.type_id, 0x17, mode)?;
                Ok(0)
            }
            0x2c => self.assignment(id, mode),
            0x2d => {
                let left = self.child(id, "left")?;
                if n.flags & 0xff00 == 0 && self.get(left)?.type_id != 15 {
                    let right = self.child(id, "right")?;
                    let rhs_return = self.visit(right, 2)?;
                    let lhs = self.get(left)?.clone();
                    let slot = lhs
                        .reference
                        .and_then(|h| self.bindings.slots.get(&h).copied())
                        .ok_or(EmitError::MissingBinding(left, "FUN_0faab81f(lhs[5])"))?;
                    let plan = assign::select_kind_2d_nonvariant_resolved(
                        lhs.type_id,
                        Some(slot),
                        Some(rhs_return & 1 != 0),
                        Some(mode as u16),
                    )?;
                    for step in plan.steps {
                        if let assign::AssignmentStep::Emit { opcode, words } = step {
                            let b: Vec<u8> = words.iter().flat_map(|w| w.to_le_bytes()).collect();
                            self.op(id, opcode, &b, plan.source_function)?;
                        } else if !matches!(
                            step,
                            assign::AssignmentStep::Evaluate {
                                node: assign::NodeRole::Right,
                                mode: 2
                            }
                        ) {
                            return Err(self.unresolved(id, 0x0fabfe7f));
                        }
                    }
                    Ok(0)
                } else {
                    // FAAB2C2 temporarily gives the assignment the native void type.
                    // The original restores its type descriptor, but keeps tag0x2C.
                    self.ast.nodes[id].kind = 0x2c;
                    self.ast.nodes[id].type_id = 2;
                    self.assignment(id, 1)?;
                    self.ast.nodes[id].type_id = n.type_id;
                    self.visit(left, 5)?;
                    Ok(0)
                }
            }
            0x2f..=0x31 => {
                let mut ret = 0;
                if let Some(l) = n.left {
                    ret = self.visit(l, mode)?
                }
                if let Some(r) = n.right {
                    ret = self.visit(r, mode)?
                }
                Ok(ret)
            }
            0x33 => {
                self.list(id, 1, true)?;
                Ok(0)
            }
            0x32 | 0x34 | 0x54 => self.io_builtin(id),
            0x36 => {
                self.visit(self.child(id, "left")?, 1)?;
                self.visit(self.child(id, "right")?, 1)?;
                self.plain(id, 0xd2)?;
                Ok(0)
            }
            0x37 => {
                self.list(id, mode, false)?;
                Ok(0)
            }
            0x3e => {
                let outer = self.child(id, "right")?;
                let wrapper = self.get(outer)?.clone();
                if let Some(args) = wrapper.right {
                    self.list(args, 1, false)?;
                }
                if let Some(mut arg) = wrapper.left {
                    if self.get(arg)?.kind == 0x11 {
                        arg = self.child(arg, "left")?;
                    }
                    self.word(
                        id,
                        if n.flags & 0x8000 != 0 { 0x431 } else { 0x360 },
                        self.reference(arg)?,
                    )?;
                } else {
                    self.plain(id, 0x1c3)?;
                }
                Ok(0)
            }
            0x38 => {
                let carrier = self.child(id, "right")?;
                self.visit(self.child(carrier, "right")?, 1)?;
                let key = n
                    .symbol
                    .ok_or(EmitError::MissingBinding(id, "array-lock symbol"))?;
                let ty = self.bindings.symbol_types.get(&key).copied().ok_or(
                    EmitError::MissingBinding(id, "array-lock native symbol type"),
                )?;
                self.word(id, 0x20d, self.slot(id)?)?;
                self.adjustment(id, ty, 0x17, 0)?;
                Ok(0)
            }
            0x39 => {
                self.word(id, 0x20e, self.slot(id)?)?;
                Ok(0)
            }
            0x3f => {
                if let Some(args) = n.right {
                    self.list(args, 1, false)?;
                }
                self.word(id, 0x20f, self.slot(id)?)?;
                Ok(0)
            }
            0x3a | 0x3b => {
                if let Some(args) = n.right {
                    self.list(args, 1, true)?
                }
                self.plain(id, if n.kind == 0x3a { 0x1ca } else { 0x1cb })?;
                Ok(0)
            }
            0x41 => {
                let mut input = self.bindings.cleanup_metadata.get(&id).cloned().ok_or(
                    EmitError::MissingBinding(
                        id,
                        "resolved cleanup count and ordered symbol slots",
                    ),
                )?;
                input.flags = n.flags as u16;
                let p = cl::plan_cleanup_list(input)?;
                for step in p.steps {
                    match step {
                        cl::CleanupStep::Emit {
                            opcode,
                            payload,
                            original_function,
                        } => self.op(id, opcode, &payload, original_function)?,
                        cl::CleanupStep::Words(words) => {
                            let payload: Vec<u8> =
                                words.iter().flat_map(|w| w.to_le_bytes()).collect();
                            self.append_words(id, &payload)?;
                        }
                        _ => return Err(self.unresolved(id, 0x0fabfea8)),
                    }
                }
                Ok(p.native_return)
            }
            0x42 | 0x43 => self.named_cleanup(id),
            0x44..=0x47 | 0x4c | 0x55 | 0x56 => self.argument_builtin(id, mode),
            0x48..=0x4b => {
                if let Some(args) = n.right {
                    self.list(args, 1, true)?
                }
                self.plain(
                    id,
                    match n.kind {
                        0x48 => 0x158,
                        0x49 => 0x15a,
                        0x4a => 0x159,
                        _ => 0x15b,
                    },
                )?;
                if n.type_id != 2 {
                    self.return_argument(id, 1)?
                }
                Ok(0)
            }
            0x4d | 0x5e => {
                self.visit(self.child(id, "right")?, 1)?;
                self.plain(id, if n.kind == 0x4d { 0x23d } else { 0x40a })?;
                Ok(0)
            }
            0x4e | 0x5c => {
                self.plain(id, if n.kind == 0x4e { 0x23e } else { 0x162 })?;
                Ok(0)
            }
            0x4f | 0x50 | 0x53 | 0x57 | 0x58 | 0x59 => {
                if let Some(args) = n.right {
                    self.list(args, 1, true)?
                }
                let op = match n.kind {
                    0x4f => 0xfb,
                    0x50 => 0xfa,
                    0x53 => {
                        if n.flags & 0x4000 == 0 {
                            0x1c0
                        } else {
                            0x1bf
                        }
                    }
                    0x59 => 0x1c1,
                    0x58 => {
                        if n.flags & 0x4000 == 0 {
                            0x3ff
                        } else {
                            0x400
                        }
                    }
                    _ => {
                        if n.flags & 0x4000 == 0 {
                            if h { 0x3fb } else { 0x3fd }
                        } else {
                            if h { 0x3fc } else { 0x3fe }
                        }
                    }
                };
                if matches!(n.kind, 0x57 | 0x58) && n.flags & 0x4000 != 0 {
                    self.word(id, op, self.slot(id)?)?;
                    self.adjustment(id, n.type_id, 0x17, mode)?;
                } else {
                    self.plain(id, op)?;
                    if n.kind == 0x57 {
                        self.adjustment(id, n.type_id, 0, mode)?;
                    }
                }
                Ok(0)
            }
            0x51 | 0x52 => self.get_put(id),
            0x5f => {
                self.visit(self.child(id, "right")?, mode)?;
                self.plain(id, 0x40b)?;
                Ok(0)
            }
            0x5a => self.redim(id),
            0x5d => {
                self.visit(self.child(id, "left")?, 5)?;
                let key = n.symbol.ok_or(EmitError::MissingBinding(
                    id,
                    "FUN_0fb0f0f7 type descriptor",
                ))?;
                let ty = self
                    .bindings
                    .symbol_types
                    .get(&key)
                    .copied()
                    .ok_or(EmitError::MissingBinding(id, "FUN_0fb0f0f7 type"))?;
                let opcode = match ty {
                    15 => Some(0x3cd),
                    16 => Some(0x3cc),
                    18 | 23 => Some(0x3cf),
                    22 => Some(0x3ce),
                    _ => None,
                };
                if let Some(opcode) = opcode {
                    self.plain(id, opcode)?;
                }
                Ok(0)
            }
            0x63 => {
                let child = self.child(id, "left")?;
                self.visit(child, 1)?;
                self.word(
                    id,
                    if self.get(child)?.type_id == 15 {
                        0x16f
                    } else {
                        0x38d
                    },
                    self.reference(id)?,
                )?;
                Ok(0)
            }
            0x61 => self.member_call(id, mode),
            0x65 => self.visit(self.child(id, "left")?, mode),
            0x66 => {
                self.word(id, 0x2f4, self.reference(id)?)?;
                Ok(0)
            }
            0x67 => {
                self.visit(self.child(id, "left")?, 5)?;
                self.word(id, 0x2f5, self.reference(id)?)?;
                Ok(0)
            }
            0x68 => self.property(id, mode),
            0x6a => self.index(id, mode),
            0x6b..=0x6e => self.latebound(id, mode),
            0x60 | 0x69 => self.address_expression(id, mode),
            0x72 => {
                let target = n
                    .symbol
                    .and_then(|h| self.bindings.bound_nodes.get(&h).copied())
                    .ok_or(EmitError::MissingBinding(id, "FUN_0fab5210"))?;
                self.address_expression(target, 2)?;
                self.typed(id, mode)
            }
            0x73 => {
                if let Literal::SpecialWord(w) = n.literal {
                    self.word(id, 0x266, w)?;
                    Ok(0)
                } else {
                    Err(EmitError::InvalidPayload(id))
                }
            }
            _ => Err(self.unresolved(
                id,
                match n.kind {
                    0x2c => 0x0fac0827,
                    0x2d => 0x0fabfe7f,
                    0x32 | 0x34 | 0x54 => 0x0fac409d,
                    0x3e => 0x0fabf2d2,
                    0x41 => 0x0fabfea8,
                    0x42 | 0x43 => 0x0fb0b52f,
                    0x5a => 0x0faeb01b,
                    0x60 => 0x0fac35b5,
                    0x61 => 0x0fabf2d2,
                    0x69 => 0x0fac13f1,
                    _ => 0x0fabf2d2,
                },
            )),
        }
    }
    fn unresolved(&self, id: NodeId, function: u32) -> EmitError {
        EmitError::Unresolved {
            node: id,
            kind: self.ast.nodes[id].kind,
            function,
        }
    }
    fn address_plan(
        &mut self,
        id: NodeId,
        descriptor: ad::AddressDescriptor,
        mode: u16,
        flags: u32,
        ty: u16,
    ) -> Result<(), EmitError> {
        let mut metadata = self
            .bindings
            .address_metadata
            .get(&id)
            .copied()
            .unwrap_or_default();
        let effective_ty = if ty == 18 && metadata.type_18_is_special == Some(true) {
            23
        } else {
            ty
        };
        if mode == 4 && metadata.mode4_lookup.is_none() {
            metadata.mode4_lookup = tables::address_mode4_byte(effective_ty, flags);
        }
        let p = ad::select_address(ad::AddressInput {
            descriptor,
            mode,
            flags,
            native_type: ty,
            metadata,
        })?;
        for i in p.instructions {
            let payload: Vec<u8> = i.words.iter().flat_map(|w| w.to_le_bytes()).collect();
            self.op(id, i.opcode, &payload, 0x0fac13f1)?;
        }
        Ok(())
    }
    fn prepare_address(&mut self, id: NodeId) -> Result<ad::AddressDescriptor, EmitError> {
        if !self.preparing.insert(id) {
            return Err(EmitError::Cycle(id));
        }
        if self.preparing.len() > 256 {
            return Err(EmitError::RecursionLimit);
        }
        let result = self.prepare_address_impl(id);
        self.preparing.remove(&id);
        result
    }
    /// FAC3B64 reference expression, including its prefix and resulting descriptor.
    fn reference_prefix_descriptor(
        &mut self,
        mut id: NodeId,
    ) -> Result<ad::AddressDescriptor, EmitError> {
        if self.get(id)?.kind == 0x31 {
            self.visit(self.child(id, "left")?, 0)?;
            id = self.child(id, "right")?;
        }
        let n = self.get(id)?.clone();
        if n.type_id == 22 {
            if n.flags & 1 == 0 {
                self.visit(id, 6)?;
                let mut d = crate::references::zero_descriptor();
                d.kind = 12;
                return Ok(d);
            } else {
                let mut d = if matches!(n.kind, 0x60 | 0x69) {
                    self.prepare_address(id)?
                } else {
                    crate::references::zero_descriptor()
                };
                d.flags_at_4 |= 5;
                return Ok(d);
            }
        } else if n.kind != 0x35 {
            if n.kind == 0x11 {
                let mut target = self.child(id, "left")?;
                if self.get(target)?.kind == 0x12 {
                    target = self.child(target, "left")?;
                }
                if self.get(target)?.kind == 0x61 {
                    self.ast.nodes[target].type_id = 2;
                    let key = self.get(target)?.symbol;
                    self.visit(target, 1)?;
                    target = key
                        .and_then(|h| self.bindings.bound_nodes.get(&h).copied())
                        .ok_or(EmitError::MissingBinding(target, "FUN_0fab5210(node[8])"))?;
                    self.ast.nodes[target].flags |= 1;
                }
                if self.get(target)?.flags & 1 != 0 {
                    if matches!(self.get(target)?.kind, 0x60 | 0x69) {
                        return self.prepare_address(target);
                    }
                } else if self.get(target)?.kind != 0x6f {
                    self.value_wrapper(target, 6)?;
                    let mut d = crate::references::zero_descriptor();
                    d.kind = 12;
                    return Ok(d);
                }
            } else {
                self.visit(id, 6)?;
                let mut d = crate::references::zero_descriptor();
                d.kind = 12;
                return Ok(d);
            }
        }
        Ok(crate::references::zero_descriptor())
    }
    fn prepare_address_impl(&mut self, id: NodeId) -> Result<ad::AddressDescriptor, EmitError> {
        let n = self.get(id)?.clone();
        if n.kind == 0x60 {
            if let Some(mut m) = self.bindings.native_references.get(&id).copied() {
                let incoming = if let Some(prefix) = n.left {
                    self.reference_prefix_descriptor(prefix)?
                } else {
                    crate::references::zero_descriptor()
                };
                self.ast.nodes[id].flags &= !0x1000;
                if m.symbol_slot.is_none() {
                    m.symbol_slot = n
                        .reference
                        .and_then(|h| self.bindings.slots.get(&h).copied());
                }
                if m.auxiliary_slot.is_none() {
                    m.auxiliary_slot = n.symbol.and_then(|h| self.bindings.slots.get(&h).copied());
                }
                let plan = crate::references::select_reference(n.type_id, n.flags, incoming, m)
                    .map_err(EmitError::Reference)?;
                for step in plan.prefix {
                    match step {
                        crate::references::ReferenceStep::Address(d) => {
                            self.address_plan(id, d, 6, 0, 0)?
                        }
                        crate::references::ReferenceStep::Emit(op) => {
                            self.op(id, op, &[], 0x0fac41e0)?
                        }
                    }
                }
                return Ok(plan.descriptor);
            }
            if let Some(m) = self.bindings.storage_references.get(&id).copied() {
                if !(1..=3).contains(&m.storage_class) {
                    return Err(EmitError::Reference(
                        crate::references::ReferenceError::UnresolvedStorageClass(m.storage_class),
                    ));
                }
                if let Some(prefix) = n.left {
                    self.reference_prefix_descriptor(prefix)?;
                }
                self.ast.nodes[id].flags &= !0x1000;
                let key = n
                    .reference
                    .ok_or(EmitError::MissingBinding(id, "FUN_0faab81f(node[5])"))?;
                let slot = self.word_binding(id, key)?;
                let auxiliary = n.symbol.and_then(|h| self.bindings.slots.get(&h).copied());
                return crate::references::select_common_storage_reference(
                    n.type_id, n.flags, slot, auxiliary, m,
                )
                .map_err(EmitError::Reference);
            }
        }
        if n.kind == 0x69 {
            if let Some(args) = n.right {
                self.list(args, 1, true)?;
            }
            self.visit(self.child(id, "left")?, 1)?;
            let mut d = ad::AddressDescriptor {
                kind: 0,
                flags_at_4: 0,
                word_at_6: 0,
                word_at_8: 0,
                word_at_10: 0,
                word_at_12: 0,
            };
            if n.flags & 0x2000 == 0 {
                if n.count == 1 {
                    d.kind = 10;
                    if n.flags & 0x8000 != 0 && n.symbol.is_some() {
                        d.word_at_6 = 1;
                        d.word_at_8 = self.slot(id)?;
                    }
                } else {
                    d.kind = 9;
                    d.word_at_6 = n.count;
                }
            } else {
                d.kind = 11;
                d.word_at_6 = n.count;
                let h = n
                    .symbol
                    .ok_or(EmitError::MissingBinding(id, "node[6] reference"))?;
                d.word_at_8 = self
                    .bindings
                    .references
                    .get(&h)
                    .copied()
                    .ok_or(EmitError::MissingBinding(id, "FUN_0fac2e29(node[6])"))?;
            }
            if n.type_id == 22 {
                d.flags_at_4 |= 5;
            }
            Ok(d)
        } else if n.kind == 0x60 && n.left.is_none() {
            // FAC0FA8 always clears this flag before returning its descriptor.
            self.ast.nodes[id].flags &= !0x1000;
            self.bindings
                .prepared_addresses
                .get(&id)
                .copied()
                .ok_or(EmitError::MissingBinding(
                    id,
                    "pure prepared FUN_0fac0fa8 descriptor",
                ))
        } else {
            Err(self.unresolved(id, 0x0fac0f35))
        }
    }
    fn address_expression(&mut self, id: NodeId, mode: i32) -> Result<u32, EmitError> {
        let n = self.get(id)?.clone();
        if n.kind == 0x60 && n.flags & 0x400 != 0 {
            let result = self
                .bindings
                .signature_descriptors
                .get(&id)
                .copied()
                .ok_or(EmitError::MissingBinding(
                    id,
                    "FUN_0fac35b5 signature descriptor",
                ))?;
            let descriptor = result.map_err(|status| EmitError::NativeHelperFailure {
                node: id,
                function: 0x0fac35b5,
                status,
            })?;
            self.op(id, 0x2ac, &descriptor.to_le_bytes(), 0x0fac35b5)?;
            return Ok(0);
        }
        let d = self.prepare_address(id)?;
        let flags = if n.kind == 0x60 {
            self.get(id)?.flags & 0xffff
        } else if n.flags & 0x8000 != 0 {
            if n.flags & 0x1000 != 0 {
                0x3000
            } else {
                0x1000
            }
        } else {
            0
        };
        self.address_plan(
            id,
            d,
            u16::try_from(mode)
                .map_err(|_| EmitError::Address(ad::AddressError::UnknownMode(mode as u16)))?,
            flags,
            n.type_id,
        )?;
        Ok(u32::from(
            (10..=12).contains(&n.type_id)
                && mode != 1
                && mode != 3
                && (n.kind == 0x69 || mode == 2),
        ))
    }
    fn assignment(&mut self, id: NodeId, mode: i32) -> Result<u32, EmitError> {
        let n = self.get(id)?.clone();
        let left = self.child(id, "left")?;
        let right = self.child(id, "right")?;
        let lhs = self.get(left)?.clone();
        let rhs = self.get(right)?.clone();
        let mut m = self
            .bindings
            .assignment_metadata
            .get(&id)
            .copied()
            .unwrap_or_default();
        let fast = n.flags & 0x200 != 0
            && rhs.kind == 0x60
            && m.rhs_special_call == Some(true)
            && m.lhs_address_kind == Some(1);
        let mut rhs_done = false;
        if !fast {
            m.rhs_emission_low_bit = Some(self.visit(right, 2)? & 1 != 0);
            rhs_done = true;
        }
        let mut descriptor = None;
        let p = assign::select_assignment(assign::AssignmentInput {
            assignment_type: n.type_id,
            flags: n.flags as u16,
            context_mode: mode as u16,
            lhs_kind: lhs.kind,
            lhs_type: lhs.type_id,
            lhs_flags: lhs.flags as u16,
            rhs_kind: rhs.kind,
            rhs_type: rhs.type_id,
            has_assignment_descriptor: n.symbol.is_some(),
            lhs_is_11_over_6a: lhs.kind == 0x11
                && lhs
                    .left
                    .is_some_and(|c| self.ast.nodes.get(c).is_some_and(|n| n.kind == 0x6a)),
            metadata: m,
        })?;
        for step in p.steps {
            match step {
                assign::AssignmentStep::Evaluate { node, mode } => {
                    let target = match node {
                        assign::NodeRole::Left => left,
                        assign::NodeRole::Right => right,
                        assign::NodeRole::IndexedBase => self.child(left, "left")?,
                    };
                    if target != right || !rhs_done {
                        self.visit(target, mode as i32)?;
                    }
                }
                assign::AssignmentStep::Address {
                    mode,
                    flags,
                    type_id,
                } => {
                    let d = if let Some(d) = descriptor {
                        d
                    } else {
                        let d = self.prepare_address(left)?;
                        descriptor = Some(d);
                        d
                    };
                    self.address_plan(left, d, mode, flags, type_id)?;
                }
                assign::AssignmentStep::Emit { opcode, words } => {
                    let b: Vec<u8> = words.iter().flat_map(|w| w.to_le_bytes()).collect();
                    self.op(id, opcode, &b, p.source_function)?;
                }
                assign::AssignmentStep::Convert { .. } => {
                    return Err(self.unresolved(id, 0x0fac0827));
                }
            }
        }
        Ok(0)
    }
    fn raw64(&self, id: NodeId) -> Result<[u8; 8], EmitError> {
        match self.get(id)?.literal {
            Literal::Raw64(b) => Ok(b),
            _ => Err(EmitError::InvalidPayload(id)),
        }
    }
    fn typed(&mut self, id: NodeId, mode: i32) -> Result<u32, EmitError> {
        let n = self.get(id)?.clone();
        let l = self.child(id, "left")?;
        let r = n.right;
        self.visit(l, 2)?;
        if let Some(r) = r {
            self.visit(r, 2)?;
        }
        let (op, slot) = tables::select_typed(tables::TypedInput {
            kind: n.kind,
            result_type: n.type_id,
            left_type: self.get(l)?.type_id,
            right_type: r.map(|r| self.get(r).map(|n| n.type_id)).transpose()?,
            flags: n.flags,
            slot: if n.type_id == 15 {
                Some(self.slot(id)?)
            } else {
                None
            },
        })?;
        self.op(
            id,
            op,
            &slot.map(|s| s.to_le_bytes().to_vec()).unwrap_or_default(),
            0x0fac2a60,
        )?;
        self.adjustment(id, n.type_id, 0, mode)
    }
    fn variant(&mut self, id: NodeId, mode: i32) -> Result<(), EmitError> {
        let n = self.get(id)?.clone();
        let slot = self.slot(id)?;
        let (tag, b, string) = match n.literal {
            Literal::Variant {
                tag,
                bytes,
                string_reference,
            } => (tag, bytes, string_reference),
            _ => return Err(EmitError::InvalidPayload(id)),
        };
        let (op, len) = match tag {
            0 => (Some(0x167), 0),
            1 => (Some(0x164), 0),
            2 => (Some(0x3c0), 2),
            3 => (Some(0x3c1), 4),
            4 => (Some(0x3c2), 4),
            5 => (Some(0x3c4), 8),
            6 => (Some(0x3c3), 8),
            7 => (Some(0x3c5), 8),
            8 => (Some(0x3c6), 2),
            10 if n.flags & 0x8000 != 0 => (Some(0x168), 0),
            11 => (
                Some(if u16::from_le_bytes([b[0], b[1]]) == 0 {
                    0x166
                } else {
                    0x165
                }),
                0,
            ),
            17 => (Some(0x33d), 2),
            _ => (None, 0),
        };
        if let Some(op) = op {
            let mut bytes = slot.to_le_bytes().to_vec();
            if tag == 8 {
                let v = string
                    .and_then(|h| self.bindings.references.get(&h).copied())
                    .ok_or(EmitError::MissingBinding(id, "FUN_0fab268c / FUN_0fac2e29"))?;
                bytes.extend(v.to_le_bytes())
            } else if tag == 17 {
                bytes.extend((b[0] as u16).to_le_bytes())
            } else {
                bytes.extend_from_slice(&b[..len])
            }
            self.op(id, op, &bytes, 0x0fabf2d2)?;
        }
        if n.flags & 0x4000 != 0 {
            self.plain(id, 0x202)?
        }
        self.adjustment(id, 15, 0, mode)?;
        Ok(())
    }
    fn conversion(&mut self, id: NodeId, mode: i32) -> Result<u32, EmitError> {
        let n = self.get(id)?.clone();
        let child = self.child(id, "left")?;
        let c = self.get(child)?.clone();
        let mut optimized = false;
        if n.type_id == 15
            && tables::AST_FLAGS
                .get(c.kind as usize)
                .is_some_and(|f| f & 1 != 0)
            && n.flags & 0xff00 == 0
        {
            let b = match c.literal {
                Literal::Integer(v) => {
                    let mut b = [0; 8];
                    b[..4].copy_from_slice(&v.to_le_bytes());
                    b
                }
                Literal::Raw64(b) => b,
                Literal::None if c.kind == 4 => [0; 8],
                _ => return Err(EmitError::InvalidPayload(child)),
            };
            let p = cv::select_constant_conversion(cv::ConstantConversionInput {
                source_type: c.type_id,
                source_ast_id: c.kind,
                source_flags_word: c.flags,
                literal_bytes: b,
                destination_slot: Some(self.slot(id)?),
                interned_string: c
                    .reference
                    .and_then(|h| self.bindings.references.get(&h).copied()),
            })?;
            if let Some(p) = p {
                for i in p.instructions {
                    self.op(id, i.opcode, &i.payload, p.source_function)?
                }
                optimized = true;
            }
        }
        if !optimized {
            self.visit(child, 2)?;
            if n.flags & 0x4000 != 0 {
                let op = if n.type_id == 10 {
                    0x13c + tables::normalized_type(c.type_id)?
                } else if c.type_id == 15 {
                    0x144
                        + *tables::TYPE_INDEX
                            .get(n.type_id as usize)
                            .ok_or(tables::SelectionError::UnknownType(n.type_id))?
                } else if n.type_id == 11 {
                    match c.type_id {
                        10 => 0x13a,
                        11 => 0x13b,
                        13 => 0x139,
                        _ => tables::CONVERSION_BASE[4] + tables::normalized_type(c.type_id)?,
                    }
                } else {
                    // FB341BA uses the caller mode verbatim in this native fallback.
                    u16::try_from(mode).map_err(|_| EmitError::InvalidPayload(id))?
                };
                self.plain(id, op)?;
            } else {
                let category = (n.flags & 0x700) >> 8;
                match category {
                    0 => {
                        let mut m = self
                            .bindings
                            .conversion_metadata
                            .get(&id)
                            .copied()
                            .unwrap_or_default();
                        if n.type_id == 15 {
                            m.destination_slot = Some(self.slot(id)?)
                        }
                        let p = cv::select_conversion(cv::ConversionInput {
                            destination_type: n.type_id,
                            source_type: c.type_id,
                            destination_flags_word: n.flags,
                            metadata: m,
                        })?;
                        for i in p.instructions {
                            self.op(id, i.opcode, &i.payload, p.source_function)?
                        }
                    }
                    1 | 3 | 4 | 5 => self.word(
                        id,
                        match category {
                            1 => 0x2fe,
                            3 => 0x2f9,
                            4 => 0x2fa,
                            _ => 0x2fc,
                        },
                        self.slot(id)?,
                    )?,
                    2 => self.plain(id, 0x2fd)?,
                    6 => {
                        self.word(id, 0x160 - u16::from(c.type_id != 15), self.slot(id)?)?;
                        if n.type_id != 2 {
                            let v = n
                                .symbol
                                .and_then(|h| self.bindings.bound_nodes.get(&h).copied())
                                .ok_or(EmitError::MissingBinding(id, "FUN_0fab5210"))?;
                            self.visit(v, mode)?;
                        }
                    }
                    7 => self.plain(id, 0x41b)?,
                    _ => unreachable!(),
                }
            }
        }
        // Shared continuation at FABF6C0: all specialized exits also run this.
        if n.flags & 0x8000 != 0 && n.type_id == 15 {
            self.plain(id, 0x202)?
        }
        self.adjustment(id, n.type_id, 0, mode)
    }
    fn load_address_or_value(&mut self, id: NodeId, mode: i32) -> Result<u32, EmitError> {
        let n = self.get(id)?.clone();
        let child = self.child(id, "left")?;
        let c = self.get(child)?.clone();
        let h = n.flags & 0x8000 != 0;
        match (n.flags & 0x700) >> 8 {
            0 => {
                if !h {
                    self.visit(child, 1)?;
                } else if (c.kind == 0x60 && c.flags & 0x2000 != 0)
                    || (c.kind == 0x69 && c.flags & 0x8000 != 0)
                    || c.kind == 0x5e
                {
                    self.visit(child, 1)?;
                    self.plain(id, 0x18c)?;
                } else {
                    self.visit(child, 3)?;
                }
                Ok(0)
            }
            1 => {
                self.visit(child, 1)?;
                let m = self.bindings.conversion_metadata.get(&id).copied().ok_or(
                    EmitError::MissingBinding(id, "load-reference type metadata"),
                )?;
                let descriptor = m
                    .source_type_descriptor
                    .ok_or(EmitError::MissingBinding(id, "FUN_0fab8628(source[2])"))?;
                let category = descriptor & 0xbfff;
                if !h {
                    let (op, type_word, extra) = if category == 0x24 {
                        (
                            0x433,
                            m.source_reference
                                .ok_or(EmitError::MissingBinding(id, "FUN_0fb8e6b0"))?,
                            None,
                        )
                    } else if category == 0x2024 || category == 0x2009 {
                        (
                            0x43a,
                            descriptor,
                            Some(m.source_reference.ok_or(EmitError::MissingBinding(
                                id,
                                "FUN_0fb8e6b0/FUN_0fb8e64d",
                            ))?),
                        )
                    } else {
                        (0x294, descriptor, None)
                    };
                    let mut payload = self.slot(id)?.to_le_bytes().to_vec();
                    payload.extend(type_word.to_le_bytes());
                    if let Some(word) = extra {
                        payload.extend(word.to_le_bytes());
                    }
                    self.op(id, op, &payload, 0x0fabf2d2)?;
                } else if category == 0x24 {
                    let mut payload = descriptor.to_le_bytes().to_vec();
                    payload.extend(
                        m.source_reference
                            .ok_or(EmitError::MissingBinding(id, "FUN_0fb8e6b0"))?
                            .to_le_bytes(),
                    );
                    self.op(id, 0x432, &payload, 0x0fabf2d2)?;
                } else if category == 0x2024 || category == 0x2009 {
                    let mut payload = self.slot(id)?.to_le_bytes().to_vec();
                    payload.extend(descriptor.to_le_bytes());
                    payload.extend(
                        m.source_reference
                            .ok_or(EmitError::MissingBinding(id, "FUN_0fb8e6b0/FUN_0fb8e64d"))?
                            .to_le_bytes(),
                    );
                    self.op(id, 0x43a, &payload, 0x0fabf2d2)?;
                    self.plain(id, 0x18c)?;
                } else {
                    self.word(id, 0x293, descriptor)?;
                }
                Ok(0)
            }
            2 => {
                self.visit(child, 3)?;
                Ok(0)
            }
            3 => {
                self.visit(child, 3)?;
                self.word(id, 0x2c6, self.slot(id)?)?;
                Ok(0)
            }
            4 => {
                self.ast.nodes[child].flags |= 0x1000;
                self.visit(child, 3)?;
                Ok(0)
            }
            _ => {
                let _ = mode;
                Ok(0)
            }
        }
    }
    fn list(&mut self, id: NodeId, mode: i32, reverse: bool) -> Result<(), EmitError> {
        let mut cursor = Some(id);
        let mut items = Vec::new();
        let mut seen = BTreeSet::new();
        while let Some(v) = cursor {
            if !seen.insert(v) {
                return Err(EmitError::Cycle(v));
            }
            let n = self.get(v)?;
            if matches!(n.kind, 0x33 | 0x37) {
                if let Some(l) = n.left {
                    items.push(l)
                }
                cursor = n.right
            } else {
                items.push(v);
                cursor = None
            }
        }
        if reverse {
            items.reverse()
        }
        for item in items {
            self.visit(item, mode)?;
        }
        Ok(())
    }
    fn value_wrapper(&mut self, id: NodeId, mode: i32) -> Result<(), EmitError> {
        let n = self.get(id)?.clone();
        match n.kind {
            0x12 => {
                self.visit(self.child(id, "left")?, if mode == 5 { 6 } else { mode })?;
            }
            0x60 | 0x69 => {
                let d = self.prepare_address(id)?;
                self.address_plan(
                    id,
                    d,
                    mode as u16,
                    if n.kind == 0x69 && n.flags & 0x8000 != 0 {
                        0x1000
                    } else {
                        0
                    },
                    n.type_id,
                )?;
            }
            5 => self.variant(id, mode)?,
            _ => {
                self.visit(id, if n.type_id == 15 { 1 } else { mode })?;
            }
        }
        Ok(())
    }
    fn append_words(&mut self, id: NodeId, payload: &[u8]) -> Result<(), EmitError> {
        if self.out.bytes.len() + payload.len() > 65535 {
            return Err(EmitError::OutputTooLarge);
        }
        self.out.bytes.extend_from_slice(payload);
        let instruction = self
            .out
            .instructions
            .last_mut()
            .ok_or(EmitError::InvalidPayload(id))?;
        instruction.operands.extend_from_slice(payload);
        Ok(())
    }
    fn named_cleanup(&mut self, id: NodeId) -> Result<u32, EmitError> {
        let n = self.get(id)?.clone();
        let outer = self.child(id, "right")?;
        let mut name = self.child(outer, "left")?;
        if self.get(name)?.kind == 0x11 {
            name = self.child(name, "left")?;
        }
        let index = self.reference(name)?;
        let rhs = self.child(outer, "right")?;
        let mut probe = rhs;
        let mut seen = BTreeSet::new();
        while matches!(self.get(probe)?.kind, 0x11 | 0x12) {
            if !seen.insert(probe) {
                return Err(EmitError::Cycle(probe));
            }
            probe = self.child(probe, "left")?;
        }
        if self.get(probe)?.kind == 0x60 && n.type_id == 2 {
            let special = self
                .bindings
                .symbol_special
                .get(&probe)
                .copied()
                .ok_or(EmitError::MissingBinding(probe, "FUN_0fab0b42"))?;
            if special {
                let key = self
                    .get(probe)?
                    .reference
                    .ok_or(EmitError::MissingBinding(probe, "rhs[5] symbol"))?;
                let mut payload = self.word_binding(probe, key)?.to_le_bytes().to_vec();
                payload.extend(index.to_le_bytes());
                self.op(
                    id,
                    if n.kind == 0x42 { 0x2ff } else { 0x3f6 },
                    &payload,
                    0x0fb0b52f,
                )?;
                return Ok(0);
            }
        }
        self.value_wrapper(self.child(rhs, "left")?, 5)?;
        self.op(id, 0x42a, &index.to_le_bytes(), 0x0fb0b52f)?;
        self.adjustment(id, n.type_id, 0x17, 1)?;
        Ok(0)
    }
    fn member_call(&mut self, id: NodeId, mode: i32) -> Result<u32, EmitError> {
        let n = self.get(id)?.clone();
        let mut metadata = self
            .bindings
            .member_metadata
            .get(&id)
            .copied()
            .ok_or(EmitError::MissingBinding(id, "bound member-call metadata"))?;
        if metadata.result_type_index.is_none() {
            metadata.result_type_index = tables::TYPE_INDEX
                .get(n.type_id as usize)
                .map(|v| u32::from(*v));
        }
        if metadata.target_bytes.is_none() {
            metadata.target_bytes = n
                .left
                .and_then(|v| self.ast.nodes.get(v))
                .and_then(|v| tables::ARGUMENT_BYTES.get(v.type_id as usize))
                .copied();
        }
        if metadata.symbol_slot.is_none() && n.symbol.is_some() {
            metadata.symbol_slot = n.symbol.and_then(|h| self.bindings.slots.get(&h).copied());
        }
        if metadata.argument_bytes.is_none() {
            metadata.argument_bytes = Some(self.argument_bytes(n.right)?);
        }
        let table = self
            .bindings
            .member_base_table
            .as_ref()
            .unwrap_or(&mc::BASE_OPCODE_SNAPSHOT);
        let plan = mc::select_member_call(
            mc::MemberInput {
                result_type: n.type_id,
                flags: n.flags as u16,
                context_mode: mode as u16,
                has_arguments: n.right.is_some(),
                word7: n.count,
                metadata,
            },
            table,
        )?;
        let mut ret = 0;
        for step in plan.steps {
            match step {
                mc::MemberStep::Arguments { helper, mode } => {
                    if let Some(args) = n.right {
                        self.list(args, mode as i32, helper == 0x0fac34c0)?;
                    }
                }
                mc::MemberStep::Target { mode } => {
                    self.visit(self.child(id, "left")?, mode as i32)?;
                }
                mc::MemberStep::Emit { opcode, words } => {
                    let b: Vec<u8> = words.iter().flat_map(|w| w.to_le_bytes()).collect();
                    self.op(id, opcode, &b, 0x0fabf2d2)?;
                }
                mc::MemberStep::Convert {
                    source_type,
                    destination_type,
                    context_mode,
                } => {
                    ret = self.adjustment(
                        id,
                        source_type,
                        i32::from(destination_type),
                        i32::from(context_mode),
                    )?;
                }
                mc::MemberStep::EvaluateSymbol { context_mode } => {
                    let target = n
                        .symbol
                        .and_then(|k| self.bindings.bound_nodes.get(&k).copied())
                        .ok_or(EmitError::MissingBinding(id, "FUN_0fab5210(node[8])"))?;
                    ret = self.visit(target, i32::from(context_mode))?;
                }
            }
        }
        Ok(ret)
    }
    fn argument_bytes(&self, mut cursor: Option<NodeId>) -> Result<u16, EmitError> {
        let mut seen = BTreeSet::new();
        let mut total = 0u16;
        while let Some(id) = cursor {
            if !seen.insert(id) {
                return Err(EmitError::Cycle(id));
            }
            let node = self.get(id)?;
            let item = if node.kind == 0x37 || node.kind == 0x33 {
                cursor = node.right;
                node.left
            } else {
                cursor = None;
                Some(id)
            };
            if let Some(item) = item {
                let ty = self.get(item)?.type_id;
                let size = *tables::ARGUMENT_BYTES
                    .get(ty as usize)
                    .ok_or(tables::SelectionError::UnknownType(ty))?;
                total = total.wrapping_add(size);
            }
        }
        Ok(total)
    }
    fn return_argument(&mut self, id: NodeId, mut index: usize) -> Result<(), EmitError> {
        let n = self.get(id)?.clone();
        let mut arg = self.child(id, "right")?;
        while index > 1 {
            arg = self.child(arg, "right")?;
            index -= 1;
        }
        if index == 1 && self.get(arg)?.kind == 0x37 {
            arg = self.child(arg, "left")?
        }
        if matches!(self.get(arg)?.kind, 0x11 | 0x2d) {
            arg = self.child(arg, "left")?
        }
        self.visit(arg, if n.type_id == 23 { 5 } else { 2 })?;
        Ok(())
    }
    fn argument_builtin(&mut self, id: NodeId, mode: i32) -> Result<u32, EmitError> {
        let n = self.get(id)?.clone();
        let op = match n.kind {
            0x44 => 0x3f5,
            0x45 => {
                if n.flags & 0x8000 != 0 {
                    0x437
                } else {
                    0x2ca
                }
            }
            0x46 => 0x15d,
            0x47 => 0x15e,
            0x4c => 0x35d,
            0x55 => 0x35e,
            0x56 if n.flags & 0x4000 == 0 => ((n.flags & 0x8000 | 0x6f0000) >> 14) as u16,
            0x56 => {
                if let Some(args) = n.right {
                    self.list(args, 1, true)?
                }
                self.plain(id, 0x1bb + if n.flags & 0x8000 != 0 { 2 } else { 0 })?;
                return Ok(0);
            }
            _ => unreachable!(),
        };
        let args = self.child(id, "right")?;
        if let Some(rest) = self.get(args)?.right {
            self.list(rest, 1, false)?
        }
        let mut arg = self.child(args, "left")?;
        if self.get(arg)?.kind == 0x11 {
            arg = self.child(arg, "left")?
        }
        let a = self.get(arg)?.clone();
        match a.kind {
            1 => {
                if let Literal::Integer(v) = a.literal {
                    self.word(id, op, v as u16)?
                } else {
                    return Err(EmitError::InvalidPayload(arg));
                }
            }
            0x6f => self.word(id, op, self.reference(arg)?)?,
            _ => {}
        }
        if matches!(n.kind, 0x44..=0x47) && n.type_id != 2 {
            self.return_argument(id, 2)?;
        }
        let _ = mode;
        Ok(0)
    }
    fn get_put(&mut self, id: NodeId) -> Result<u32, EmitError> {
        let n = self.get(id)?.clone();
        let category = ((n.flags & 0x700) >> 8) as usize;
        let base = *tables::GET_PUT_BASE
            .get(category)
            .ok_or(self.unresolved(id, 0x0fac4125))?;
        let opcode = base - if n.kind == 0x51 { 2 } else { 0 };
        if category == 2 || category == 3 {
            let outer = self.child(id, "right")?;
            if let Some(args) = self.get(outer)?.right {
                self.list(args, 1, true)?;
            }
            let index = self.reference(self.child(outer, "left")?)?;
            self.op(id, opcode, &index.to_le_bytes(), 0x0fac4125)?;
        } else {
            if let Some(args) = n.right {
                self.list(args, 1, true)?;
            }
            self.op(id, opcode, &[], 0x0fac4125)?;
        }
        Ok(0)
    }
    fn literal_word(&self, id: NodeId) -> Result<u16, EmitError> {
        match self.get(id)?.literal {
            Literal::Integer(value) => Ok(value as u16),
            Literal::SpecialWord(value) => Ok(value),
            _ => Err(EmitError::InvalidPayload(id)),
        }
    }
    fn redim_descriptor(&self, id: NodeId, fallback: NodeId) -> Result<u16, EmitError> {
        match self.get(id)?.kind {
            1 => self.literal_word(id),
            0x11 => self.reference(self.child(id, "left")?),
            0x6f => self.reference(id),
            // Native fallback truncates a pointer. Arena indices are not pointers.
            _ => self
                .bindings
                .native_pointer_words
                .get(&fallback)
                .copied()
                .ok_or(EmitError::MissingBinding(
                    fallback,
                    "FUN_0faeb01b native pointer low word",
                )),
        }
    }
    fn redim(&mut self, id: NodeId) -> Result<u32, EmitError> {
        let n = self.get(id)?.clone();
        let first_cell = self.child(id, "right")?;
        let first = self.literal_word(self.child(first_cell, "left")?)?;
        let second_cell = self.child(first_cell, "right")?;
        let preserve = u16::from(n.flags & 0x8000 != 0);
        let (target, bounds, opcode, operands) = if n.flags & 0x4000 == 0 {
            let second = self.literal_word(self.child(second_cell, "left")?)?;
            let target_cell = self.child(second_cell, "right")?;
            let target = self.child(target_cell, "left")?;
            let descriptor_cell = self.child(target_cell, "right")?;
            let descriptor = self.redim_descriptor(self.child(descriptor_cell, "left")?, target)?;
            let count_cell = self.child(descriptor_cell, "right")?;
            let count = self.literal_word(self.child(count_cell, "left")?)?;
            (
                target,
                self.get(count_cell)?.right,
                0x38e + preserve,
                vec![count, descriptor, second, first],
            )
        } else {
            let target = self.child(second_cell, "left")?;
            let count_cell = self.child(second_cell, "right")?;
            let count = self.literal_word(self.child(count_cell, "left")?)?;
            if n.flags & 0x2000 == 0 {
                (
                    target,
                    self.get(count_cell)?.right,
                    0x390 + preserve,
                    vec![count, first],
                )
            } else {
                let descriptor_cell = self.child(count_cell, "right")?;
                let descriptor =
                    self.redim_descriptor(self.child(descriptor_cell, "left")?, descriptor_cell)?;
                (
                    target,
                    self.get(descriptor_cell)?.right,
                    0x43b + preserve,
                    vec![count, first, descriptor],
                )
            }
        };
        if let Some(bounds) = bounds {
            self.list(bounds, 1, true)?;
        }
        self.visit(target, 1)?;
        let bytes = operands
            .into_iter()
            .flat_map(u16::to_le_bytes)
            .collect::<Vec<_>>();
        self.op(id, opcode, &bytes, 0x0faeb01b)?;
        Ok(0)
    }
    fn io_builtin(&mut self, id: NodeId) -> Result<u32, EmitError> {
        let n = self.get(id)?.clone();
        let op = match n.kind {
            0x32 => {
                if n.flags & 0x8000 != 0 {
                    0x40e
                } else {
                    0x40d
                }
            }
            0x34 => 0x40f,
            0x54 => 0x410,
            _ => unreachable!(),
        };
        let mut cursor = n.right;
        let mut seen = BTreeSet::new();
        let mut size = 0u16;
        while let Some(a) = cursor {
            if !seen.insert(a) {
                return Err(EmitError::Cycle(a));
            }
            let an = self.get(a)?;
            let arg = if matches!(an.kind, 0x33 | 0x37) {
                cursor = an.right;
                an.left
            } else {
                cursor = None;
                Some(a)
            };
            if let Some(arg) = arg {
                let ty = self.get(arg)?.type_id;
                let width = if ty == 15 {
                    tables::ARGUMENT_BYTES[23]
                } else {
                    *tables::ARGUMENT_BYTES
                        .get(ty as usize)
                        .ok_or(tables::SelectionError::UnknownType(ty))?
                };
                size = size.wrapping_add(width);
            }
        }
        size = size.wrapping_add(tables::ARGUMENT_BYTES[7]);
        if let Some(args) = n.right {
            self.list(args, 1, true)?;
        }
        if op == 0x40d && n.flags & 0x4000 != 0 {
            self.op(id, 0x411, &[], 0x0fac409d)?;
            size = size.wrapping_add(tables::ARGUMENT_BYTES[23]);
        }
        let target = self.child(id, "left")?;
        let r = self.reference(target)?;
        let mut payload = r.to_le_bytes().to_vec();
        payload.extend(size.to_le_bytes());
        self.op(id, op, &payload, 0x0fac409d)?;
        Ok(0)
    }
    fn property(&mut self, id: NodeId, mode: i32) -> Result<u32, EmitError> {
        let n = self.get(id)?.clone();
        let child = self.child(id, "left")?;
        self.visit(child, 1)?;
        if mode == 6 {
            self.plain(id, 0x29f)?;
            return Ok(0);
        }
        let mut with_reference = false;
        let opcode =
            if n.type_id == 22 {
                match self.get(child)?.type_id {
                    15 => {
                        let (a, b) =
                            self.bindings.property_checks.get(&id).copied().ok_or(
                                EmitError::MissingBinding(id, "FUN_0fab5494/FUN_0fab54ae"),
                            )?;
                        if a {
                            0x134
                        } else if b {
                            0x171
                        } else {
                            with_reference = true;
                            0x2f3
                        }
                    }
                    22 => {
                        with_reference = true;
                        0x2f2
                    }
                    _ => u16::try_from(mode).map_err(|_| EmitError::InvalidPayload(id))?,
                }
            } else {
                u16::try_from(mode).map_err(|_| EmitError::InvalidPayload(id))?
            };
        if with_reference {
            self.word(id, opcode, self.reference(id)?)?
        } else {
            self.plain(id, opcode)?
        }
        Ok(0)
    }
    fn index(&mut self, id: NodeId, mode: i32) -> Result<u32, EmitError> {
        let n = self.get(id)?.clone();
        if let Some(args) = n.right {
            self.list(args, 3, false)?
        }
        self.visit(self.child(id, "left")?, 1)?;
        let category = (n.flags & 0x300) >> 8;
        if category == 1 || category == 2 {
            self.word(id, if category == 1 { 0x3b0 } else { 0x3b1 }, n.count)?;
            return Ok(0);
        }
        let slot = if n.symbol.is_some() {
            self.slot(id)?
        } else {
            0
        };
        let mut payload = slot.to_le_bytes().to_vec();
        let opcode = if n.flags & 0x8000 == 0 {
            if category == 0 { 0x3ae } else { 0x3af }
        } else {
            let binding = match n.member {
                Some(Member::Reference(h)) => h,
                _ => return Err(EmitError::MissingBinding(id, "FUN_0faab81f(node[7])")),
            };
            payload.extend(self.word_binding(id, binding)?.to_le_bytes());
            0x3f2
        };
        payload.extend(n.count.to_le_bytes());
        self.op(id, opcode, &payload, 0x0fabf2d2)?;
        self.adjustment(id, n.type_id, 0x17, mode)?;
        Ok(0)
    }
    fn latebound(&mut self, id: NodeId, mode: i32) -> Result<u32, EmitError> {
        let n = self.get(id)?.clone();
        let target = self.child(id, "left")?;
        let v = self.get(target)?.type_id == 15;
        let d = n.flags & 0x8000 != 0;
        let l = n.flags & 0x4000 != 0;
        let (opcode, force, slot) = select_latebound(n.kind, n.flags, v, n.count != 0)
            .ok_or(self.unresolved(id, 0x0fac3e10))?;
        // FAC3F4C consumes only kind 0x37 lists, not 0x33.
        let mut cursor = n.right;
        let mut count = n.count;
        let mut seen = BTreeSet::new();
        while let Some(arg) = cursor {
            if count == 0 {
                break;
            }
            if !seen.insert(arg) {
                return Err(EmitError::Cycle(arg));
            }
            let a = self.get(arg)?.clone();
            if a.kind == 0x37 {
                self.visit(self.child(arg, "left")?, 3)?;
                cursor = a.right;
                count = count.wrapping_sub(1)
            } else {
                self.visit(arg, 3)?;
                cursor = None;
            }
        }
        if n.kind == 0x6c || n.kind == 0x6d {
            let mut arg = self.child(id, "right")?;
            let mut seen = BTreeSet::new();
            while self.get(arg)?.kind == 0x37 {
                if !seen.insert(arg) {
                    return Err(EmitError::Cycle(arg));
                }
                arg = self
                    .get(arg)?
                    .right
                    .or(self.get(arg)?.left)
                    .ok_or(EmitError::MissingChild(arg, "list tail"))?;
            }
            self.visit(arg, 3)?;
        }
        self.visit(target, if v { 5 } else { 6 })?;
        let mut payload = Vec::new();
        if l {
            let size = if d {
                n.layout_count.wrapping_mul(4).wrapping_add(6)
            } else {
                n.layout_count.wrapping_add(2).wrapping_mul(2)
            };
            payload.extend(size.wrapping_add(if slot { 2 } else { 0 }).to_le_bytes());
        }
        if slot {
            payload.extend(self.slot(id)?.to_le_bytes());
        }
        match n.member {
            Some(Member::Direct(value)) if d => payload.extend(value.to_le_bytes()),
            Some(Member::Reference(key)) if !d => payload.extend(
                self.bindings
                    .references
                    .get(&key)
                    .copied()
                    .ok_or(EmitError::MissingBinding(id, "FUN_0fac2e29(node[7])"))?
                    .to_le_bytes(),
            ),
            _ => return Err(EmitError::MissingBinding(id, "member identity")),
        }
        if n.count != 0 || force {
            payload.extend(n.count.to_le_bytes());
        }
        if l {
            let mut count = n.layout_count;
            let mut seen = BTreeSet::new();
            while let Some(a) = cursor {
                if count == 0 {
                    break;
                }
                if !seen.insert(a) {
                    return Err(EmitError::Cycle(a));
                }
                let mut arg = a;
                let an = self.get(a)?;
                if an.kind == 0x37 {
                    cursor = an.right;
                    arg = self.child(a, "left")?
                } else {
                    cursor = None
                }
                if self.get(arg)?.kind == 0x11 {
                    arg = self.child(arg, "left")?
                }
                let an = self.get(arg)?;
                match an.kind {
                    1 => {
                        if let Literal::Integer(v) = an.literal {
                            payload.extend(v.to_le_bytes())
                        } else {
                            return Err(EmitError::InvalidPayload(arg));
                        }
                    }
                    0x6f => payload.extend(self.reference(arg)?.to_le_bytes()),
                    _ => {}
                }
                count = count.wrapping_sub(1);
            }
        }
        self.op(id, opcode, &payload, 0x0fac3e10)?;
        if n.kind == 0x6b {
            self.adjustment(id, n.type_id, 0x17, mode)?;
        }
        Ok(0)
    }
}
/// Exact finite selectors in FABF2D2 cases 6B..6E; operand emission is FAC3E10.
pub fn select_latebound(
    kind: u16,
    flags: u32,
    target_variant: bool,
    count_nonzero: bool,
) -> Option<(u16, bool, bool)> {
    let d = flags & 0x8000 != 0;
    let l = flags & 0x4000 != 0;
    let n = u16::from(count_nonzero);
    Some(match kind {
        0x6b => (
            if d {
                if l { 0x3ab } else { 0x3a1 + n }
            } else if l {
                0x3a7
            } else if target_variant {
                0x441 + n - if flags & 0x800 != 0 { 4 } else { 0 }
            } else {
                0x399 + n
            },
            false,
            true,
        ),
        0x6c => (
            if d {
                if flags & 0x2000 == 0 {
                    0x3a3
                } else {
                    0x3a4 | if l { 8 } else { 0 }
                }
            } else if flags & 0x2000 == 0 {
                if target_variant { 0x443 } else { 0x39b }
            } else if target_variant {
                0x444
            } else {
                0x39c + if l { 12 } else { 0 }
            },
            flags & 0x2000 != 0,
            false,
        ),
        0x6d => (
            if l {
                0x3a9 | if d { 4 } else { 0 }
            } else if target_variant {
                0x445
            } else {
                0x39d + if d { 8 } else { 0 }
            },
            true,
            false,
        ),
        0x6e => (
            if flags & 0x1000 != 0 {
                0x40c
            } else if l {
                0x3a6 + if d { 4 } else { 0 }
            } else {
                0x398 + if d { 8 } else { 0 }
            },
            true,
            false,
        ),
        _ => return None,
    })
}
